import { chromium } from 'playwright';
const URL = process.env.DDZ_URL ?? 'http://127.0.0.1:4174/jiaye-tianxia/';
const KEY = 'jiaye-tianxia-save-v1';
const S = process.env.S + '/ddz';
const PREFIX = process.env.PREFIX ?? 'v2';
const browser = await chromium.launch({ headless: true });
const save = { screen: 'home', selectedLordId: 'lvbu', gold: 50000, homeLevel: 4, equippedWeaponId: 'fangtian', ownedPartnerIds: ['diaochan', 'zhurong'], claimedQuestIds: [], day: 11, battleWins: 3, battleLosses: 0, soundEnabled: false, tutorialDone: true, lastScreen: 'home', eventLog: [], lastSavedAt: Date.now() };
for (const [name, vp] of [['landscape', { width: 844, height: 390 }], ['portrait', { width: 390, height: 844 }]]) {
  const ctx = await browser.newContext({ viewport: vp, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(URL, { waitUntil: 'domcontentloaded' });
  await page.evaluate(([k, s]) => localStorage.setItem(k, JSON.stringify(s)), [KEY, save]);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(600);
  await page.getByRole('button', { name: /出征讨伐/ }).first().click();
  await page.getByRole('button', { name: /中级场/ }).click();
  await page.getByRole('button', { name: /^进入斗地主/ }).click();
  await page.getByText('斗地主牌局').first().waitFor();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${S}/${PREFIX}-${name}-start.png` });
  await page.getByRole('button', { name: '提示' }).click().catch(() => {});
  await page.getByRole('button', { name: '出牌' }).click().catch(() => {});
  await page.waitForTimeout(2600);
  await page.screenshot({ path: `${S}/${PREFIX}-${name}-mid.png` });
  console.log(name, 'errors', errors.length, errors.slice(0, 2).join(' | '));
  await ctx.close();
}
await browser.close();
